@dataclass(frozen=True)
class KindThresholds:
    min_words: int
    max_words: int
    min_mean_word_len: float
    max_mean_word_len: float
    max_symbol_ratio: float
    max_bullet_line_frac: float
    max_ellipsis_line_frac: float
    min_alpha_word_frac: float
    min_stopwords: int
    max_dup_line_frac: float
    max_dup_para_frac: float
    max_dup_line_char_frac: float
    max_dup_para_char_frac: float
    max_top_ngram_char_frac: dict[int, float]
    max_dup_ngram_char_frac: dict[int, float]
    max_line_len: int
    min_english_function_word_frac: float
    max_non_latin_letter_frac: float


@dataclass(frozen=True)
class CodeThresholds:
    min_chars: int
    min_nonblank_lines: int
    max_bytes: int
    max_mean_line_len: float
    max_line_len: int
    min_alnum_frac: float
    max_numeric_token_frac: float
    max_non_latin_letter_frac: float


@dataclass(frozen=True)
class QualityConfig:
    max_replacement_char_frac: float
    max_mojibake_per_kchar: float
    max_base64_char_frac: float
    max_spam_terms_per_kword: float
    math_latex_per_kword: float
    technical_code_line_frac: float
    kinds: dict[str, KindThresholds]
    code: CodeThresholds
    curated_repetition: dict[str, Any]

    @staticmethod
    def from_dict(raw: dict[str, Any]) -> QualityConfig:
        def kind(entry: dict[str, Any]) -> KindThresholds:
            values = dict(entry)
            values["max_top_ngram_char_frac"] = {
                int(k): float(v) for k, v in entry["max_top_ngram_char_frac"].items()
            }
            values["max_dup_ngram_char_frac"] = {
                int(k): float(v) for k, v in entry["max_dup_ngram_char_frac"].items()
            }
            return KindThresholds(**values)

        return QualityConfig(
            max_replacement_char_frac=raw["max_replacement_char_frac"],
            max_mojibake_per_kchar=raw["max_mojibake_per_kchar"],
            max_base64_char_frac=raw["max_base64_char_frac"],
            max_spam_terms_per_kword=raw["max_spam_terms_per_kword"],
            math_latex_per_kword=raw["math_latex_per_kword"],
            technical_code_line_frac=raw["technical_code_line_frac"],
            kinds={name: kind(raw["kinds"][name]) for name in ("prose", "math", "technical")},
            code=CodeThresholds(**raw["code"]),
            curated_repetition={
                key: ({int(k): float(v) for k, v in value.items()} if isinstance(value, dict) else value)
                for key, value in raw["curated"].items()
            },
        )


@dataclass
class QualityResult:
    kind: str
    reasons: list[str]
    features: dict[str, float]


