_HAS_ALNUM_RE = re.compile(r"[^\W_]")
_BULLET_LINE_RE = re.compile(
    r"^[ \t]*(?:[\u2022\u2023\u25e6\u2043\u2219\-*\u00b7]|\d+[.)])[ \t]", re.MULTILINE
)
_ELLIPSIS_LINE_RE = re.compile(r"(?:\.\.\.|\u2026)[ \t]*$", re.MULTILINE)
_NONBLANK_LINE_RE = re.compile(r"^[ \t]*\S", re.MULTILINE)
# Whitespace-delimited tokens made only of ASCII digits and punctuation. Non-ASCII
# characters count as letters here, which keeps the scan linear and cheap.
# Pure markup tokens (table pipes, bullets, rules, heading marks) are layout, not words,
# and are left out of the alphabetic-word ratio's denominator.
_MARKUP_TOKEN_RE = re.compile(r"(?<!\S)(?:[|*#>\-\u2013\u2014:]+|={3,})(?!\S)")
_LETTER_FREE_TOKEN_RE = re.compile(r"(?<!\S)[^\sA-Za-z\u0080-\U0010ffff]+(?!\S)")


def _word_set_hashes(words: frozenset[str]) -> U64:
    return np.unique(word_hashes(sorted(words)))


_STOPWORD_HASHES = _word_set_hashes(_STOPWORDS)
_FUNCTION_WORD_HASHES = _word_set_hashes(ENGLISH_FUNCTION_WORDS)
_SPAM_HASHES = _word_set_hashes(_SPAM_TERMS)


def _codepoint_stats(text: str) -> tuple[int, int, int, int]:
    """Counts of (digits, Latin letters, non-Latin letters, alphanumerics), vectorized.

    Non-Latin letters are approximated by Unicode script blocks (Greek through
    Ethiopic, CJK, Hangul, kana, Arabic presentation forms); that is enough for a
    script-share signal and avoids a per-character Python loop."""
    cps = np.frombuffer(text.encode("utf-32-le", "surrogatepass"), dtype=np.uint32)
    digits = int(np.count_nonzero((cps >= 48) & (cps <= 57)))
    folded = cps | 32
    ascii_letters = int(np.count_nonzero((folded >= 97) & (folded <= 122) & (cps < 128)))
    latin_ext = int(np.count_nonzero((cps >= 0xC0) & (cps <= 0x24F) & (cps != 0xD7) & (cps != 0xF7)))
    non_latin = int(
        np.count_nonzero(
            ((cps >= 0x370) & (cps <= 0x1FFF) & ~((cps >= 0x1D00) & (cps <= 0x1EFF)))
            | ((cps >= 0x2E80) & (cps <= 0xD7FF))
            | ((cps >= 0xF900) & (cps <= 0xFAFF))
            | ((cps >= 0xFB50) & (cps <= 0xFDFF))
            | ((cps >= 0xFE70) & (cps <= 0xFEFF))
            | ((cps >= 0xFF66) & (cps <= 0xFFDC))
        )
    )
    latin = ascii_letters + latin_ext
    return digits, latin, non_latin, digits + latin + non_latin


def _alpha_word_frac(text: str, n_words: int) -> float:
    markup = len(_MARKUP_TOKEN_RE.findall(text))
    counted = n_words - markup
    if counted <= 0:
        return 0.0
    letter_free = len(_LETTER_FREE_TOKEN_RE.findall(text)) - markup
    return float(1 - letter_free / counted)


def compute_features(text: str, sig_hashes: U64) -> dict[str, float]:
    n_chars = len(text)
    words = text.split()
    n_words = len(words)
    long_tokens = [w for w in words if len(w) >= 120]
    kwords = max(n_words, 1) / 1000.0
    n_sig = max(int(sig_hashes.size), 1)
    lines = text.split("\n")
    nonblank = len(_NONBLANK_LINE_RE.findall(text))
    nonblank_chars = sum(len(line) for line in lines if line.strip()) if nonblank else 0
    digits, latin, non_latin, alnum = _codepoint_stats(text)
    letters = latin + non_latin
    return {
        "n_chars": float(n_chars),
        "n_words": float(n_words),
        "n_lines": float(len(lines)),
        "n_nonblank_lines": float(nonblank),
        "max_line_len": float(max(map(len, lines), default=0)),
        "mean_line_len": float(nonblank_chars / nonblank) if nonblank else 0.0,
        "mean_word_len": float(len("".join(words)) / n_words) if n_words else 0.0,
        "alpha_word_frac": _alpha_word_frac(text, n_words),
        "stopwords": float(np.count_nonzero(np.isin(sig_hashes, _STOPWORD_HASHES))),
        "english_function_word_frac": float(
            np.count_nonzero(np.isin(sig_hashes, _FUNCTION_WORD_HASHES)) / n_sig
        ),
        "symbol_ratio": float((text.count("#") + text.count("...") + text.count("\u2026")) / n_words)
        if n_words
        else 0.0,
        "bullet_line_frac": float(len(_BULLET_LINE_RE.findall(text)) / nonblank) if nonblank else 0.0,
        "ellipsis_line_frac": float(len(_ELLIPSIS_LINE_RE.findall(text)) / nonblank) if nonblank else 0.0,
        "code_line_frac": float(len(_CODE_LINE_RE.findall(text)) / nonblank) if nonblank else 0.0,
        "latex_per_kword": float(len(_LATEX_RE.findall(text)) / kwords),
        "replacement_char_frac": float(text.count("\ufffd") / n_chars) if n_chars else 0.0,
        "mojibake_per_kchar": float(len(_MOJIBAKE_RE.findall(text)) / (n_chars / 1000.0))
        if n_chars and ("\u00c3" in text or "\u00c2" in text or "\u00e2\u20ac" in text)
        else 0.0,
        "base64_char_frac": float(
            sum(len(m) for w in long_tokens for m in _BASE64_RUN_RE.findall(w)) / n_chars
        )
        if n_chars
        else 0.0,
        "spam_terms_per_kword": float(np.count_nonzero(np.isin(sig_hashes, _SPAM_HASHES)) / kwords),
        "alnum_frac": float(alnum / n_chars) if n_chars else 0.0,
        "digit_frac": float(digits / n_chars) if n_chars else 0.0,
        "non_latin_letter_frac": float(non_latin / letters) if letters else 0.0,
    }


def evaluate(
    text: str,
    signature_hashes: U64,
    signature_lengths: npt.NDArray[np.int64],
    config: QualityConfig,
    source_kind: str | None = None,
    path: str | None = None,
    curated: bool = False,
) -> QualityResult:
    """Check one stored document; the signature arrays are the word hashes and word
    lengths of its matching signature. ``curated`` sources (human-edited open
    textbooks) use the curated repetition limits, because learning objectives,
    key points and summaries deliberately restate the body text."""
    features = compute_features(text, signature_hashes)
    kind = classify_kind(features, source_kind, config)
    reasons: list[str] = []

    if not text.strip():
        return QualityResult(kind, ["quality.empty"], features)
    if features["replacement_char_frac"] > config.max_replacement_char_frac:
        reasons.append("quality.corrupt_decoding")
    if features["mojibake_per_kchar"] > config.max_mojibake_per_kchar:
        reasons.append("quality.mojibake")
    if features["base64_char_frac"] > config.max_base64_char_frac:
        reasons.append("quality.binary_or_base64")
    # A web-spam lexicon: crypto libraries and technical Q&A use these words legitimately.
    if kind in ("prose", "math") and features["spam_terms_per_kword"] > config.max_spam_terms_per_kword:
        reasons.append("quality.spam_terms")

    if kind == "code":
        reasons.extend(_code_reasons(text, features, config.code, path))
    else:
        thresholds = config.kinds[kind]
        if curated:
            thresholds = dataclasses.replace(thresholds, **config.curated_repetition)
        reasons.extend(_text_reasons(text, features, signature_hashes, signature_lengths, thresholds, kind))
    return QualityResult(kind, reasons, features)


def _text_reasons(
    text: str,
    f: dict[str, float],
    signature_hashes: U64,
    signature_lengths: npt.NDArray[np.int64],
    t: KindThresholds,
    kind: str,
) -> list[str]:
    reasons: list[str] = []
    p = f"quality.{kind}"
    if f["n_words"] < t.min_words:
        reasons.append(f"{p}.too_short")
    if f["n_words"] > t.max_words:
        reasons.append(f"{p}.too_long")
    if not t.min_mean_word_len <= f["mean_word_len"] <= t.max_mean_word_len:
        reasons.append(f"{p}.mean_word_length")
    if f["symbol_ratio"] > t.max_symbol_ratio:
        reasons.append(f"{p}.symbol_ratio")
    if f["bullet_line_frac"] > t.max_bullet_line_frac:
        reasons.append(f"{p}.bullet_lines")
    if f["ellipsis_line_frac"] > t.max_ellipsis_line_frac:
        reasons.append(f"{p}.ellipsis_lines")
    if f["alpha_word_frac"] < t.min_alpha_word_frac:
        reasons.append(f"{p}.alpha_words")
    if f["stopwords"] < t.min_stopwords:
        reasons.append(f"{p}.stopwords")
    if f["max_line_len"] > t.max_line_len:
        reasons.append(f"{p}.line_length")
    if f["english_function_word_frac"] < t.min_english_function_word_frac:
        reasons.append(f"{p}.not_english")
    if f["non_latin_letter_frac"] > t.max_non_latin_letter_frac:
        reasons.append(f"{p}.non_latin_script")

    # Lines without any letter or digit (table rules, lone bullets) repeat by nature
    # and carry no boilerplate content, so they do not count as duplicate lines.
    lines = [line.strip() for line in text.split("\n") if _HAS_ALNUM_RE.search(line)]
    paragraphs = [para.strip() for para in re.split(r"\n\s*\n", text) if para.strip()]
    total = len(text)
    dup_line_frac, dup_line_chars = _dup_fraction(lines, total)
    dup_para_frac, dup_para_chars = _dup_fraction(paragraphs, total)
    f.update(
        dup_line_frac=dup_line_frac,
        dup_line_char_frac=dup_line_chars,
        dup_para_frac=dup_para_frac,
        dup_para_char_frac=dup_para_chars,
    )
    if dup_line_frac > t.max_dup_line_frac or dup_line_chars > t.max_dup_line_char_frac:
        reasons.append(f"{p}.duplicate_lines")
    if dup_para_frac > t.max_dup_para_frac or dup_para_chars > t.max_dup_para_char_frac:
        reasons.append(f"{p}.duplicate_paragraphs")

    # Fractions are of the whole document's signature characters, also when notation
    # is set aside below, so a short page is not judged on a shrunken denominator.
    total_sig = int(signature_lengths.sum())
    if kind == "math":
        # Notation (symbols and subscripted names of up to three characters, Greek
        # letters, operator and font commands) recurs by nature in mathematics, so
        # repeated n-grams are found among the remaining words.
        keep = (signature_lengths >= 4) & ~np.isin(signature_hashes, _MATH_NOTATION_HASHES)
        signature_hashes, signature_lengths = signature_hashes[keep], signature_lengths[keep]
    top, dup = _top_and_dup_ngram_fracs(
        signature_hashes, signature_lengths, total_sig, t.max_top_ngram_char_frac, t.max_dup_ngram_char_frac
    )
    for n, limit in t.max_top_ngram_char_frac.items():
        f[f"top_{n}gram_char_frac"] = top[n]
        if top[n] > limit:
            reasons.append(f"{p}.top_ngram_repetition")
            break
    for n, limit in t.max_dup_ngram_char_frac.items():
        f[f"dup_{n}gram_char_frac"] = dup[n]
        if dup[n] > limit:
            reasons.append(f"{p}.duplicate_ngrams")
            break
    return reasons


def _code_reasons(text: str, f: dict[str, float], t: CodeThresholds, path: str | None) -> list[str]:
    reasons: list[str] = []
    if f["n_chars"] < t.min_chars or f["n_nonblank_lines"] < t.min_nonblank_lines:
        reasons.append("quality.code.too_short")
    if len(text.encode("utf-8")) > t.max_bytes:
        reasons.append("quality.code.too_large")
    if f["mean_line_len"] > t.max_mean_line_len or f["max_line_len"] > t.max_line_len:
        reasons.append("quality.code.long_lines")
    if f["alnum_frac"] < t.min_alnum_frac:
        reasons.append("quality.code.low_alnum")
    if f["non_latin_letter_frac"] > t.max_non_latin_letter_frac:
        reasons.append("quality.code.non_latin_script")
    if _GENERATED_RE.search(text[:2000]):
        reasons.append("quality.code.generated")
    if path and _MINIFIED_PATH_RE.search(path):
        reasons.append("quality.code.vendored_or_minified")
    if path and _LOCKFILE_RE.search(path):
        reasons.append("quality.code.lockfile")
    tokens = text.split()
    if tokens:
        numeric = sum(1 for tok in tokens if _HEXISH_RE.fullmatch(tok.strip(",;[](){}")))
        f["numeric_token_frac"] = numeric / len(tokens)
        if f["numeric_token_frac"] > t.max_numeric_token_frac:
            reasons.append("quality.code.data_heavy")
    return reasons
