"""Layered, domain-aware quality filtering.

Every document is assigned a *kind* first (prose, math, technical, code) and is
then checked against the thresholds for that kind, so equations, tables, terse
API documentation and source code are not judged by prose heuristics. The
prose repetition rules follow Gopher (Rae et al., 2021); the code rules follow
the StarCoder / The Stack file filters. Thresholds live in configs/pipeline.toml.

``evaluate`` returns all failing reason codes, not just the first, so rejection
statistics show overlapping causes.
"""

