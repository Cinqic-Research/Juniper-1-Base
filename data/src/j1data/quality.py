def _top_and_dup_ngram_fracs(
    hashes: U64,
    lengths: npt.NDArray[np.int64],
    total_chars: int,
    top_ns: dict[int, float],
    dup_ns: dict[int, float],
) -> tuple[dict[int, float], dict[int, float]]:
    top: dict[int, float] = {}
    dup: dict[int, float] = {}
    count = hashes.size
    if total_chars == 0:
        return dict.fromkeys(top_ns, 0.0), dict.fromkeys(dup_ns, 0.0)
    prefix = np.concatenate(([0], np.cumsum(lengths)))
    for n in sorted(set(top_ns) | set(dup_ns)):
        if count < n:
            if n in top_ns:
                top[n] = 0.0
            if n in dup_ns:
                dup[n] = 0.0
            continue
        grams = ngram_hashes(hashes, n)
        _, first_index, inverse, counts = np.unique(
            grams, return_index=True, return_inverse=True, return_counts=True
        )
        if n in top_ns:
            best = int(np.argmax(counts))
            first = int(first_index[best])
            gram_chars = int(prefix[first + n] - prefix[first])
            top[n] = float(counts[best] * gram_chars / total_chars) if counts[best] > 1 else 0.0
        if n in dup_ns:
            # As in Gopher, only repeat occurrences count; the first occurrence is ordinary text.
            repeated = first_index[inverse] != np.arange(grams.size)
            covered = np.zeros(count + 1, dtype=np.int32)
            starts = np.flatnonzero(repeated)
            np.add.at(covered, starts, 1)
            np.add.at(covered, starts + n, -1)
            mask = np.cumsum(covered[:-1]) > 0
            dup[n] = float(lengths[mask].sum() / total_chars)
    return top, dup


def _dup_fraction(items: list[str], total_chars: int) -> tuple[float, float]:
    if not items:
        return 0.0, 0.0
    seen: Counter[str] = Counter(items)
    dup_items = sum(c - 1 for c in seen.values() if c > 1)
    dup_chars = sum(len(t) * (c - 1) for t, c in seen.items() if c > 1)
    return dup_items / len(items), (dup_chars / total_chars if total_chars else 0.0)


def classify_kind(text_features: dict[str, float], source_kind: str | None, config: QualityConfig) -> str:
    if source_kind == "code":
        return "code"
    if text_features["latex_per_kword"] >= config.math_latex_per_kword or source_kind == "math":
        return "math"
    if text_features["code_line_frac"] >= config.technical_code_line_frac or source_kind == "technical":
        return "technical"
    return "prose"


