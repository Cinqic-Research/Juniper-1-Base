def check(text: str, kind: str | None = None, path: str | None = None) -> quality.QualityResult:
    words = signature_words(text)
    hashes = word_hashes(words)
    lengths = np.fromiter((len(w) for w in words), dtype=np.int64, count=len(words))
    return quality.evaluate(text, hashes, lengths, CONFIG, kind, path)


def test_good_prose_passes() -> None:
    result = check(PROSE)
    assert result.kind == "prose" and result.reasons == []


def test_math_is_judged_as_math_and_passes() -> None:
    result = check(MATH)
    assert result.kind == "math" and result.reasons == []


def test_math_would_fail_prose_thresholds() -> None:
    # The same document under prose rules trips the alphabetic-word rule; this is
    # why kinds exist.
    words = signature_words(MATH)
    hashes = word_hashes(words)
    lengths = np.fromiter((len(w) for w in words), dtype=np.int64, count=len(words))
    features = quality.compute_features(MATH, hashes)
    reasons = quality._text_reasons(MATH, features, hashes, lengths, CONFIG.kinds["prose"], "prose")
    assert "quality.prose.alpha_words" in reasons


def test_python_source_passes_code_rules() -> None:
    result = check(PYTHON, kind="code", path="repo/src/geometry.py")
    assert result.kind == "code" and result.reasons == []


