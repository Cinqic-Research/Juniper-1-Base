def test_duplicate_ngram_measure_counts_only_repeats() -> None:
    # Two distinct halves: no repeated n-grams at all.
    words = signature_words(PROSE)
    hashes = word_hashes(words)
    lengths = np.fromiter((len(w) for w in words), dtype=np.int64, count=len(words))
    _, dup = quality._top_and_dup_ngram_fracs(hashes, lengths, int(lengths.sum()), {}, {5: 1.0})
    assert dup[5] == 0.0
    # The same paragraph twice: the second copy (half the characters) is duplicate.
    doubled = word_hashes(words + words)
    lengths2 = np.concatenate([lengths, lengths])
    _, dup = quality._top_and_dup_ngram_fracs(doubled, lengths2, int(lengths2.sum()), {}, {5: 1.0})
    assert 0.45 < dup[5] < 0.55


def test_symbol_only_lines_do_not_count_as_duplicate_lines() -> None:
    table = "\n".join(["|", PROSE, "|", "-", "-", "-", "|"])
    assert "quality.prose.duplicate_lines" not in check(table).reasons


def test_curated_profile_relaxes_only_repetition() -> None:
    restated = PROSE + "\n\nKey Points\n" + PROSE[:200]
    words = signature_words(restated)
    hashes = word_hashes(words)
    lengths = np.fromiter((len(w) for w in words), dtype=np.int64, count=len(words))
    strict = quality.evaluate(restated, hashes, lengths, CONFIG)
    curated = quality.evaluate(restated, hashes, lengths, CONFIG, curated=True)
    assert "quality.prose.duplicate_ngrams" in strict.reasons and curated.reasons == []
    short = "Key Points\nOnly a short note."
    words = signature_words(short)
    lengths = np.fromiter((len(w) for w in words), dtype=np.int64, count=len(words))
    assert (
        "quality.prose.too_short"
        in quality.evaluate(short, word_hashes(words), lengths, CONFIG, curated=True).reasons
    )


def test_markdown_table_markup_does_not_count_against_alphabetic_words() -> None:
    table = "\n".join(f"| {w} | {w}s | - |" for w in PROSE.split()[:60])
    assert quality.compute_features(table, word_hashes(signature_words(table)))["alpha_word_frac"] > 0.95
    numbers = " ".join(str(i) for i in range(200))
    assert quality.compute_features(numbers, word_hashes(signature_words(numbers)))["alpha_word_frac"] == 0.0


def test_math_notation_repetition_is_not_duplicate_text() -> None:
    rng = random.Random(4)
    vocabulary = PROSE.replace(",", "").replace(".", "").split()
    sentences = []
    for i in range(30):
        prose = " ".join(rng.choice(vocabulary) for _ in range(12))
        sentences.append(f"Lemma {i}. {prose} with \\(\\langle x_p, y_p \\rangle = \\tilde r_a\\) here.")
    result = check("We study operators on Hilbert spaces. " + " ".join(sentences))
    assert result.kind == "math"
    assert not any("duplicate_ngrams" in r for r in result.reasons)


def test_repetitive_math_spam_is_still_rejected() -> None:
    spam = "Solve for x now, best free math homework answers online, solve for x now. " * 40 + MATH
    assert any("repetition" in r or "duplicate" in r for r in check(spam).reasons)
